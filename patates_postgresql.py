def login_required(view):
    @wraps(view)
    def wrapped(*args, **kwargs):

        if "user_id" not in session:
            return redirect("/login")

        return view(*args, **kwargs)

    return wrapped


def current_user():

    if "user_id" not in session:
        return None

    conn = get_db()

    user = conn.execute(
        """
        SELECT id, username
        FROM users
        WHERE id=%s
        """,
        (session["user_id"],)
    ).fetchone()

    conn.close()

    return user


