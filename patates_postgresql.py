@app.route("/toggle/<int:id>", methods=["POST"])
@login_required
def toggle(id):

    conn = get_db()

    user_id = session["user_id"]

    today = str(date.today())


    # IDOR koruması:
    # Habit hem ID'ye hem de mevcut kullanıcıya ait olmalı.
    habit = conn.execute(
        """
        SELECT id
        FROM habits
        WHERE id=%s AND user_id=%s
        """,
        (
            id,
            user_id
        )
    ).fetchone()


    if habit is None:

        conn.close()

        return redirect("/")


    completed = conn.execute(
        """
        SELECT id
        FROM completions
        WHERE habit_id=%s AND day=%s
        """,
        (
            id,
            today
        )
    ).fetchone()


    if completed:

        conn.execute(
            """
            DELETE FROM completions
            WHERE habit_id=%s AND day=%s
            """,
            (
                id,
                today
            )
        )

    else:

        conn.execute(
            """
            INSERT INTO completions
            (habit_id, day)
            VALUES (%s, %s)
            """,
            (
                id,
                today
            )
        )


    conn.commit()

    conn.close()

    return redirect("/")


