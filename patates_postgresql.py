@app.route("/register", methods=["GET", "POST"])
def register():

    if request.method == "POST":

        username = request.form.get(
            "username",
            ""
        ).strip()

        password = request.form.get(
            "password",
            ""
        )


        # Kullanıcı adı kontrolü
        if not re.fullmatch(
            r"[A-Za-z0-9_]{3,30}",
            username
        ):

            flash(
                "Kullanıcı adı 3-30 karakter olmalı ve sadece harf, rakam ve _ içermeli.",
                "error"
            )

            return redirect("/register")


        # Şifre uzunluğu
        if len(password) < 8:

            flash(
                "Şifre en az 8 karakter olmalı.",
                "error"
            )

            return redirect("/register")


        # Şifreyi düz metin olarak kaydetmiyoruz.
        password_hash = generate_password_hash(
            password
        )


        conn = get_db()

        try:

            cursor = conn.execute(
                """
                INSERT INTO users
                (username, password_hash)
                VALUES (%s, %s)
                RETURNING id
                """,
                (
                    username,
                    password_hash
                )
            )

            conn.commit()

            session.clear()

            session["user_id"] = cursor.fetchone()["id"]

        except psycopg.errors.UniqueViolation:

            conn.close()

            flash(
                "Bu kullanıcı adı zaten kullanılıyor.",
                "error"
            )

            return redirect("/register")

        conn.close()

        return redirect("/")


    return page(
        REGISTER_HTML,
        "Kayıt Ol"
    )


