@app.route("/stats")
@login_required
def stats():

    conn = get_db()

    habits = conn.execute(
        """
        SELECT id, name
        FROM habits
        WHERE user_id=%s
        ORDER BY id DESC
        """,
        (session["user_id"],)
    ).fetchall()


    result = []


    for habit in habits:

        total = conn.execute(
            """
            SELECT COUNT(*)
            FROM completions
            WHERE habit_id=%s
            """,
            (habit["id"],)
        ).fetchone()["count"]


        result.append({
            "name": habit["name"],
            "total": total,
            "streak": calculate_streak(
                conn,
                habit["id"]
            ),
            "longest": get_longest_streak(
                conn,
                habit["id"]
            )
        })


    conn.close()


    return page(
        STATS_HTML,
        "İstatistikler",
        habits=result
    )


