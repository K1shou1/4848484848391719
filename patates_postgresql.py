def calculate_streak(conn, habit_id):

    rows = conn.execute(
        """
        SELECT day
        FROM completions
        WHERE habit_id=%s
        ORDER BY day DESC
        """,
        (habit_id,)
    ).fetchall()

    completed_days = {
        row["day"]
        for row in rows
    }

    if not completed_days:
        return 0

    current = date.today()

    # Bugün yapılmadıysa dün üzerinden seri devam edebilir.
    if str(current) not in completed_days:
        current = date.fromordinal(
            current.toordinal() - 1
        )

    streak = 0

    while str(current) in completed_days:

        streak += 1

        current = date.fromordinal(
            current.toordinal() - 1
        )

    return streak


def get_longest_streak(conn, habit_id):

    rows = conn.execute(
        """
        SELECT day
        FROM completions
        WHERE habit_id=%s
        ORDER BY day ASC
        """,
        (habit_id,)
    ).fetchall()

    longest = 0
    current_streak = 0
    previous = None

    for row in rows:

        day = date.fromisoformat(row["day"])

        if (
            previous is not None
            and (day - previous).days == 1
        ):
            current_streak += 1
        else:
            current_streak = 1

        longest = max(
            longest,
            current_streak
        )

        previous = day

    return longest


