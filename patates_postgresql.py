@app.route("/login", methods=["GET", "POST"])
def login():

    if request.method == "POST":

        username = request.form.get(
            "username",
            ""
        ).strip()

        password = request.form.get(
            "password",
            ""
        )


        conn = get_db()

        user = conn.execute(
            """
            SELECT id, username, password_hash
            FROM users
            WHERE username=%s
            """,
            (username,)
        ).fetchone()

        conn.close()


        if (
            user
            and check_password_hash(
                user["password_hash"],
                password
            )
        ):

            # Session fixation'a karşı eski session temizleniyor.
            session.clear()

            session["user_id"] = user["id"]

            return redirect("/")


        flash(
            "Kullanıcı adı veya şifre hatalı.",
            "error"
        )


    return page(
        LOGIN_HTML,
        "Giriş"
    )


