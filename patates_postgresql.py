@app.route("/")
@login_required
def home():

    conn = get_db()

    user_id = session["user_id"]

    habits = conn.execute(
        """
        SELECT id, name
        FROM habits
        WHERE user_id=%s
        ORDER BY id DESC
        """,
        (user_id,)
    ).fetchall()

    result = []

    today = str(date.today())

    for habit in habits:

        completed = conn.execute(
            """
            SELECT 1
            FROM completions
            WHERE habit_id=%s AND day=%s
            """,
            (habit["id"], today)
        ).fetchone()

        result.append({
            "id": habit["id"],
            "name": habit["name"],
            "completed": completed is not None,
            "streak": calculate_streak(
                conn,
                habit["id"]
            )
        })

    conn.close()

    return page(
        HOME_HTML,
        "Alışkanlık Takibi",
        habits=result
    )


